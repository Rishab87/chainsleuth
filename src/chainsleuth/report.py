"""Render reports/RESULTS.md (all numbers) from reports/results/*.json.

    uv run python -m chainsleuth.report
"""

from __future__ import annotations

from chainsleuth.config import REPORTS_DIR
from chainsleuth.pipeline import load_results


def _pm(m, k):
    return f"{m[k]['mean']:.3f} ± {m[k]['std']:.3f}"


def model_table(sections: dict) -> list[str]:
    out = ["| Model | Features / edges | F1 @0.5 | F1 (val thr.) | Precision | Recall | PR-AUC | MCC | Seeds |",
           "|---|---|---|---|---|---|---|---|---|"]
    rows = []
    for v_sec in sections.values():
        for k, v in v_sec.items():
            rows.append((k, v))
    rows.sort(key=lambda kv: -kv[1]["metrics"]["f1_at_0.5"]["mean"])
    for k, v in rows:
        m = v["metrics"]
        name, fs = k.split("|")
        out.append(f"| {name} | {fs} | {_pm(m, 'f1_at_0.5')} | {_pm(m, 'f1')} | {m['precision']['mean']:.3f} | "
                   f"{m['recall']['mean']:.3f} | {m['pr_auc']['mean']:.3f} | {m['mcc']['mean']:.3f} | {v['n_seeds']} |")
    return out


def main() -> None:
    r = load_results()
    L = ["# ChainSleuth: full results", "",
         "Auto-generated by `python -m chainsleuth.report` from `reports/results/*.json`. Test set = labelled "
         "transactions in time steps 35–49; models train on steps 1–34. *F1 @0.5* uses the default decision "
         "threshold; *F1 (val thr.)* uses the threshold that maximised F1 on validation steps 30–34 "
         "(model refit on 1–34 afterwards).", ""]
    if "eda" in r:
        e = r["eda"]
        L += ["## Dataset", "",
              f"- {e['n_nodes']:,} transactions, {e['n_edges']:,} directed edges, {e['n_features']} features, {e['n_time_steps']} time steps",
              f"- labels: {e['n_illicit']:,} illicit / {e['n_licit']:,} licit / {e['n_unknown']:,} unknown",
              f"- train (1–34): {e['train_illicit']:,} illicit, {e['train_licit']:,} licit; test (35–49): {e['test_illicit']:,} illicit, {e['test_licit']:,} licit",
              f"- edges crossing time steps: **{e['cross_step_edges']}**", "",
              "![labels](figures/labels_per_step.png)", ""]
    if "tabular" in r:
        L += ["## Feature-only models", "", "LF = 93 local features, AF = all 165, AF+G = AF + 10 graph-mining features.", ""]
        L += model_table({"tabular": r["tabular"]}) + [""]
    if "gnn" in r:
        L += ["## Graph neural networks and edge ablation", "",
              "`real` = true transaction graph; `shuffled` = destinations permuted within each time step "
              "(same degree sequence, random structure); `none` = no edges (the GNN degenerates to a per-node MLP).", ""]
        L += model_table({"gnn": r["gnn"]}) + ["", "![ablation](figures/gnn_edge_ablation.png)", ""]
    if "hybrid" in r:
        L += ["## Hybrid: tree models on AF + GraphSAGE embeddings", ""] + model_table({"hybrid": r["hybrid"]}) + [""]
    if "tabular" in r:
        L += ["![comparison](figures/model_comparison.png)", "", "![per-step](figures/per_step_f1.png)", ""]
    if "significance" in r:
        L += ["## Significance (exact McNemar test, test steps 35–49, threshold 0.5, seed 0)", "",
              "| Comparison | LightGBM right, GNN wrong | LightGBM wrong, GNN right | p-value |", "|---|---|---|---|"]
        for k, v in r["significance"].items():
            L.append(f"| {k} | {v['a_right_b_wrong']} | {v['a_wrong_b_right']} | {v['p_value']:.2e} |")
        L.append("")
    if "unsupervised" in r:
        L += ["## Unsupervised anomaly detection (no labels used)", "",
              "| Detector | Precision | Recall | F1 | PR-AUC |", "|---|---|---|---|---|"]
        for k, v in r["unsupervised"].items():
            L.append(f"| {k} | {v['precision']:.3f} | {v['recall']:.3f} | {v['f1']:.3f} | {v['pr_auc']:.3f} |")
        L += ["", f"Detectors flag the top {r['unsupervised']['isolation_forest']['flag_fraction']:.1%} most anomalous "
              "test transactions (the training illicit rate).", ""]
    if "semi" in r:
        s = r["semi"]
        L += ["## Semi-supervised self-training (XGBoost, AF)", "",
              "| Arm | Precision | Recall | F1 | PR-AUC |", "|---|---|---|---|---|"]
        for arm in ("supervised", "self_training"):
            m = s[arm]
            L.append(f"| {arm} | {m['precision']['mean']:.3f} | {m['recall']['mean']:.3f} | {_pm(m, 'f1')} | {m['pr_auc']['mean']:.3f} |")
        L += ["", f"Pseudo-labels added per round: {s['pseudo_label_log']}", ""]
    if "drift" in r:
        d = r["drift"]
        L += ["## Concept drift and adaptation", "",
              "| Strategy | mean per-step F1 (35–49) | steps 35–42 | steps 43–49 |", "|---|---|---|---|"]
        for k, v in d["strategy_summary"].items():
            L.append(f"| {k} | {v['mean_step_f1']:.3f} | {v['mean_step_f1_35_42']:.3f} | {v['mean_step_f1_43_49']:.3f} |")
        L += ["", f"ADWIN on the static model's error stream (needs labels) alarms at steps {d['adwin_steps']}; "
              f"ADWIN on its alert stream (label-free) alarms at steps {d.get('adwin_alert_steps')}.", "",
              "Alert rate per step (share of test transactions flagged): "
              + ", ".join(f"{k}: {v:.3f}" for k, v in d.get("alert_rate", {}).items()), "",
              "![drift](figures/drift.png)", ""]
    if "patterns" in r:
        p = r["patterns"]
        L += ["## Association rules → illicit (Apriori)", "",
              f"{p['n_rules']} rules with confidence ≥ 0.5 over the top XGBoost features. Top 10 by lift, with how they hold on the test steps:", "",
              "| Antecedent | Train support | Train conf. | Lift | Test support | Test conf. |", "|---|---|---|---|---|---|"]
        for rule in p["rules"][:10]:
            L.append(f"| {rule['antecedents']} | {rule['support']:.3f} | {rule['confidence']:.3f} | {rule['lift']:.2f} | "
                     f"{rule['test_support']:.3f} | {rule['test_confidence']:.3f} |")
        L.append("")
    if "explain" in r:
        L += ["## Explainability", "", "![shap](figures/shap_importance.png)", ""]
    if "gnn_explain" in r:
        L += ["GNNExplainer on the top-scored true-illicit test transactions (GraphSAGE):", "",
              "| tx_id | GraphSAGE prob | 2-hop nodes | 2-hop edges | top features |", "|---|---|---|---|---|"]
        for ex in r["gnn_explain"]["examples"]:
            L.append(f"| {ex['tx_id']} | {ex['sage_prob']:.3f} | {ex['subgraph_nodes']} | {ex['subgraph_edges']} | {', '.join(ex['top_features'])} |")
        L.append("")
    (REPORTS_DIR / "RESULTS.md").write_text("\n".join(L))
    print("wrote", REPORTS_DIR / "RESULTS.md")


if __name__ == "__main__":
    main()
